import json
from pathlib import Path
from ..models import Item


def generate_ability_files(items: list[Item]) -> dict[str, str]:
    abilities = {item.id: item.custom.on_use for item in items if item.enabled and item.kind == "custom" and item.custom and item.custom.on_use}
    if not abilities: return {}
    data = "// Generated by TBR-001 item editor.\nexport const ABILITY_DATA = " + json.dumps(abilities, ensure_ascii=False, indent=2) + ";\n"
    geometry = (Path(__file__).parents[1] / "ability_geometry.mjs").read_text(encoding="utf-8")
    context = '''let context = null;
export const setAbilityContext = value => { context = value; };
export const getAbilityContext = () => context;
'''
    runner = '''import { getAbilityContext } from "./abilityContext.js";
import { inCircle, inCone, inLine } from "./abilityGeometry.js";
import { ABILITY_DATA } from "./abilityData.js";

export function runAbility(itemId, source) {
  const ability = ABILITY_DATA[itemId]; const game = getAbilityContext();
  if (!ability || !game || !game.isEligibleSource?.(source)) return;
  const sound = ability.sound;
  if (sound?.id) game.playSound?.(source, sound.id, { volume: Number(sound.volume ?? 1), pitch: Number(sound.pitch ?? 1), scope: sound.scope ?? "source" });
  const targets = game.getPlayers?.() ?? [];
  const origin = source.location; const direction = source.getViewDirection?.() ?? { x: 0, z: 1 };
  for (const target of targets) {
    if (!game.isEligibleTarget?.(source, target)) continue;
    const shape = ability.target?.type ?? "self"; const radius = Number(ability.target?.radius ?? 0);
    const point = target.location; const hit = shape === "self" ? target.id === source.id : shape === "circle" ? inCircle(origin, point, radius) : shape === "cone" ? inCone(origin, direction, point, radius, Number(ability.target.angle ?? 90)) : shape === "line" ? inLine(origin, direction, point, radius, Number(ability.target.width ?? 1)) : shape === "look" ? game.inLook?.(source, target, radius) === true : target.id === source.id;
    if (!hit) continue;
    for (const effect of ability.effects ?? []) {
      if (effect.kind === "heal") game.heal?.(target, Number(effect.amount ?? 0));
      if (effect.kind === "potion_effect") game.addEffect?.(target, effect.id, Number(effect.duration_sec ?? 1) * 20, Math.max(0, Number(effect.level ?? 1) - 1));
    }
  }
}
'''
    component = '''import { system } from "@minecraft/server";
import { runAbility } from "./abilityRunner.js";
system.beforeEvents.startup.subscribe(({ itemComponentRegistry }) => itemComponentRegistry.registerCustomComponent("tbr:ability", { onUse(event) { runAbility(event.itemStack?.typeId ?? "", event.source); } }));
'''
    return {
        "behavior_pack/scripts/item/custom/abilityData.js": data,
        "behavior_pack/scripts/item/custom/abilityGeometry.js": geometry,
        "behavior_pack/scripts/item/custom/abilityContext.js": context,
        "behavior_pack/scripts/item/custom/abilityRunner.js": runner,
        "behavior_pack/scripts/item/custom/tbrAbility.js": component,
    }
