from collections import defaultdict
import random
import re
from ..models import Item

ENTRY = re.compile(r"\{\s*id:\s*\"([^\"]+)\"\s*,\s*amount:\s*(\d+)\s*,\s*weight:\s*([0-9.eE+-]+)\s*,\s*rarity:\s*(\d+)\s*\}")


def _js(item: Item, entry) -> str:
    return f'  {{ id: "{item.id}", amount: {entry.amount}, weight: {entry.weight:g}, rarity: {entry.rarity} }},'


def entry_signature(text: str) -> list[tuple[str, int, float, int]]:
    return [(item_id, int(amount), float(weight), int(rarity)) for item_id, amount, weight, rarity in ENTRY.findall(text)]


def leading_comments(text: str) -> str:
    lines = text.splitlines(); kept = []
    for line in lines:
        if line.startswith("//") or not line.strip(): kept.append(line)
        else: break
    return "\n".join(kept).rstrip() + ("\n" if kept else "// Generated by TBR item editor.\n")


def generate_loot_files(items: list[Item], source_texts: dict[str, str] | None = None) -> dict[str, str]:
    source_texts = source_texts or {}; grouped: dict[tuple[str, int], list[tuple[Item, object]]] = defaultdict(list)
    for item in items:
        if item.enabled:
            for entry in item.loot:
                if entry.pool in {"common", "supply"}: grouped[(entry.pool, entry.rarity)].append((item, entry))
    files: dict[str, str] = {}
    for pool in ("common", "supply"):
        for rarity in sorted({r for p, r in grouped if p == pool} or {1}):
            entries = grouped.get((pool, rarity), [])
            entries.sort(key=lambda pair: (pair[1].source_file != f"behavior_pack/scripts/item/loot/{pool}/rarity{rarity}.js", pair[1].source_index if pair[1].source_index >= 0 else 10**9))
            path = f"behavior_pack/scripts/item/loot/{pool}/rarity{rarity}.js"
            name = f"LOOT_{pool.upper()}_RARITY_{rarity}"
            files[path] = leading_comments(source_texts.get(path, "")) + f"export const {name} = Object.freeze([\n" + "\n".join(_js(item, entry) for item, entry in entries) + "\n]);\n"
    imports = []; spreads = {"common": [], "supply": []}
    for path in sorted(files):
        match = re.search(r"/(common|supply)/rarity(\d+)\.js$", path)
        if not match: continue
        pool, rarity = match.groups(); name = f"LOOT_{pool.upper()}_RARITY_{rarity}"
        imports.append(f'import {{ {name} }} from "./{pool}/rarity{rarity}.js";'); spreads[pool].append(f"...{name}")
    files["behavior_pack/scripts/item/loot/index.js"] = "\n".join(imports + ["", "// Generated by TBR item editor.", "export const lootTables = Object.freeze({", f"  common: Object.freeze([{', '.join(spreads['common'])}]),", f"  supply: Object.freeze([{', '.join(spreads['supply'])}]),", "});", ""])
    return files


def simulate_item_probability(items: list[Item], target_id: str, pool: str = "common", slots: int = 27, trials: int = 10000, seed: int = 1) -> float:
    rng = random.Random(seed); unique = {}
    for item in items:
        if item.enabled and any(entry.pool == pool for entry in item.loot): unique.setdefault(item.id, item)
    candidates = list(unique.values())
    hits = 0
    for _ in range(trials):
        selected = [item for item in candidates if rng.random() < next(entry.weight for entry in item.loot if entry.pool == pool)]
        rng.shuffle(selected)
        if any(item.id == target_id for item in selected[:slots]): hits += 1
    return hits / trials if trials else 0.0
